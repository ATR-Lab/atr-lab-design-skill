SEP = "  ·  "   # two spaces, middle dot, two spaces


def find_placeholders(obj, path="spec") -> list:
    found = []
    if isinstance(obj, str):
        for m in PLACEHOLDER_RE.findall(obj):
            found.append(f"{path}: {m}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            found += find_placeholders(v, f"{path}[{i}]")
    elif isinstance(obj, dict):
        for k, v in obj.items():
            if k in ("image", "alt_text", "image_alt"):
                continue
            found += find_placeholders(v, f"{path}.{k}")
    return found


def as_text(v) -> str:
    if v is None:
        return ""
    if isinstance(v, list):
        return SEP.join(str(x) for x in v)
    return str(v)


