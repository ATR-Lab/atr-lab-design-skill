def hex_to_rgb(h: str) -> tuple:
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _lum(rgb) -> float:
    def ch(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(c) for c in rgb[:3])
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b) -> float:
    la, lb = _lum(a), _lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


class Tokens:
    """Flattened DTCG colour tokens with aliases resolved. Access by short name."""

    SHORT = {
        "navy": "color.brand.navy", "gold": "color.brand.gold",
        "midnight": "color.ksu.midnight", "sky": "color.ksu.sky",
        "ink": "color.functional.ink", "slate": "color.functional.slate",
        "bronze": "color.functional.bronze", "mist": "color.functional.mist",
        "line": "color.functional.line", "white": "color.functional.white",
        "on_navy_secondary": "color.semantic.light.text.on-navy-secondary",
        "navy300": "color.ramp.navy.300", "gray600": "color.ramp.gray.600",
    }

    def __init__(self, path: Path = TOKENS_FILE):
        raw = json.loads(Path(path).read_text())
        flat: dict = {}

        def walk(node, prefix):
            if isinstance(node, dict):
                if "$value" in node:
                    flat[prefix] = node["$value"]
                else:
                    for k, v in node.items():
                        if not k.startswith("$"):
                            walk(v, f"{prefix}.{k}" if prefix else k)
        walk(raw, "")
        for _ in range(8):
            changed = False
            for k, v in list(flat.items()):
                if isinstance(v, str) and v.startswith("{") and v.endswith("}"):
                    flat[k] = flat[v[1:-1]]
                    changed = True
            if not changed:
                break
        self.flat = flat
        self.rgb = {k: hex_to_rgb(v) for k, v in flat.items() if isinstance(v, str) and v.startswith("#")}

    def __getattr__(self, name):
        key = self.SHORT.get(name)
        if key is None:
            raise AttributeError(name)
        return self.rgb[key]

    def hex(self, name: str) -> str:
        return self.flat[self.SHORT[name]]


