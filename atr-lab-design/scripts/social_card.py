_KERN_WARNED = False


class Face:
    """One font file: cached Pillow fonts per pixel size, metrics and kerning."""

    def __init__(self, key: str):
        self.key = key
        self.path = FONTS / FONT_FILES[key]
        if not self.path.exists():
            raise FileNotFoundError(f"brand font missing: {self.path}")
        self._fonts: dict = {}
        self._metrics: dict = {}
        self._kern: Optional[Callable[[str, str], float]] = None
        self._kern_cache: dict = {}

    def font(self, px: int) -> ImageFont.FreeTypeFont:
        f = self._fonts.get(px)
        if f is None:
            f = ImageFont.truetype(str(self.path), px)
            self._fonts[px] = f
        return f

    def metrics(self, px: int) -> dict:
        m = self._metrics.get(px)
        if m is None:
            f = self.font(px)
            cap = f.getbbox("H", anchor="ls")
            xh = f.getbbox("x", anchor="ls")
            desc = f.getbbox("gjpqy", anchor="ls")
            m = {"cap": -cap[1], "xh": -xh[1], "desc": max(desc[3], 0)}
            self._metrics[px] = m
        return m

    # -- kerning from GPOS (fontTools), in em units ------------------------
    def _build_kern(self):
        global _KERN_WARNED
        if TTFont is None:
            if not _KERN_WARNED:
                print("note: fontTools not installed; text is set without kerning", file=sys.stderr)
                _KERN_WARNED = True
            return lambda a, b: 0.0
        try:
            ft = TTFont(str(self.path), lazy=True)
            upem = ft["head"].unitsPerEm
            cmap = ft.getBestCmap()
            gpos = ft["GPOS"].table
            lookups = set()
            for fr in gpos.FeatureList.FeatureRecord:
                if fr.FeatureTag == "kern":
                    lookups.update(fr.Feature.LookupListIndex)
            groups = []
            for li in sorted(lookups):
                sts = []
                for st in gpos.LookupList.Lookup[li].SubTable:
                    if st.LookupType == 9:
                        st = st.ExtSubTable
                    if st.LookupType == 2:
                        sts.append(st)
                groups.append(sts)
        except Exception as exc:  # pragma: no cover
            print(f"note: no kerning for {self.path.name}: {exc}", file=sys.stderr)
            return lambda a, b: 0.0

        def kern(a: str, b: str) -> float:
            ga, gb = cmap.get(ord(a)), cmap.get(ord(b))
            if not ga or not gb:
                return 0.0
            total = 0
            for sts in groups:
                for st in sts:
                    cov = st.Coverage.glyphs
                    if ga not in cov:
                        continue
                    if st.Format == 1:
                        ps = st.PairSet[cov.index(ga)]
                        hit = False
                        for pvr in ps.PairValueRecord:
                            if pvr.SecondGlyph == gb:
                                v = pvr.Value1
                                total += getattr(v, "XAdvance", 0) if v else 0
                                hit = True
                                break
                        if hit:
                            break
                    else:
                        c1 = st.ClassDef1.classDefs.get(ga, 0)
                        c2 = st.ClassDef2.classDefs.get(gb, 0)
                        v = st.Class1Record[c1].Class2Record[c2].Value1
                        xa = getattr(v, "XAdvance", 0) if v else 0
                        if xa:
                            total += xa
                            break
            return total / upem
        return kern

    def kern(self, a: str, b: str) -> float:
        if self._kern is None:
            self._kern = self._build_kern()
        key = a + b
        v = self._kern_cache.get(key)
        if v is None:
            v = self._kern(a, b)
            self._kern_cache[key] = v
        return v


@lru_cache(maxsize=None)
def face(key: str) -> Face:
    return Face(key)


# --------------------------------------------------------------------------
# Type styles and typesetting
# --------------------------------------------------------------------------
@dataclass
class Style:
    face: str
    px: int
    color: tuple
    lh: float = 1.2            # line pitch as a multiple of px
    tracking: float = 0.0      # em
    upper: bool = False
    align: str = "left"
    bracket_color: Optional[tuple] = None   # muted colour for [ ] when placeholders are allowed

    def with_px(self, px: int) -> "Style":
        return Style(self.face, px, self.color, self.lh, self.tracking, self.upper, self.align, self.bracket_color)

    @property
    def pitch(self) -> int:
        return int(round(self.px * self.lh))

    @property
    def metrics(self) -> dict:
        m = dict(face(self.face).metrics(self.px))
        if self.upper:
            m["desc"] = 0
        return m


class Typesetter:
    """Measures and draws text glyph by glyph (kerning + tracking, subpixel x)."""

    def __init__(self, style: Style):
        self.style = style
        self.fc = face(style.face)
        self.font = self.fc.font(style.px)
        self.track = style.tracking * style.px

    def prep(self, text: str) -> str:
        # non-breaking space / hyphen are wrapping hints only: draw them as the plain glyphs
        text = text.replace(NBSP, " ").replace(NBHYPHEN, "-")
        return text.upper() if self.style.upper else text

    def advances(self, text: str) -> list:
        f, fc, px, tr = self.font, self.fc, self.style.px, self.track
        out = []
        for i, ch in enumerate(text):
            adv = f.getlength(ch)
            if i + 1 < len(text):
                adv += fc.kern(ch, text[i + 1]) * px
            out.append(adv + tr)
        return out

    def width(self, text: str) -> float:
        text = self.prep(text)
        if not text:
            return 0.0
        return sum(self.advances(text)) - self.track

    def draw(self, draw: ImageDraw.ImageDraw, x: float, baseline: float, text: str, color=None) -> float:
        text = self.prep(text)
        color = color or self.style.color
        bc = self.style.bracket_color
        advs = self.advances(text)
        for ch, adv in zip(text, advs):
            fill = bc if (bc and ch in "[]") else color
            if not ch.isspace():
                draw.text((x, baseline), ch, font=self.font, fill=fill, anchor="ls")
            x += adv
        return x - self.track


def wrap_paragraph(words: list, widths: list, space: float, max_w: float, balance: bool) -> list:
    """Return a list of (start, end_exclusive) word ranges. Greedy for the minimum line count,
    then (if balance) a min-raggedness DP with exactly that many lines, biased so earlier
    lines are the fuller ones (no top-light 'pyramid' headlines)."""
    n = len(words)
    if n == 0:
        return []
    pre = [0.0]
    for w in widths:
        pre.append(pre[-1] + w)

    def line_w(j, i):  # words j..i-1
        return pre[i] - pre[j] + space * (i - j - 1)

    lines = []
    j = 0
    while j < n:
        i = j + 1
        while i < n and line_w(j, i + 1) <= max_w:
            i += 1
        if line_w(j, i) > max_w:
            raise LayoutError(f"the word '{words[j]}' ({line_w(j, i):.0f} px) is wider than the column ({max_w:.0f} px)")
        lines.append((j, i))
        j = i
    L = len(lines)
    if L == 1:
        return lines
    if not balance:
        # "pretty" wrap: greedy, but never leave a lone word (or a stub under 22 % of the
        # measure) on the last line when the previous line can give up its last word.
        j, i = lines[-1]
        pj, pi = lines[-2]
        lone = i - j == 1 and NBSP not in words[j]      # a glued phrase alone is not an orphan
        stub = lone or (line_w(j, i) < 0.22 * max_w)
        if stub and pi - pj >= 3 and line_w(pi - 1, i) <= max_w:
            lines[-2] = (pj, pi - 1)
            lines[-1] = (pi - 1, i)
        return lines
    INF = float("inf")
    dp = [[INF] * (n + 1) for _ in range(L + 1)]
    back = [[-1] * (n + 1) for _ in range(L + 1)]
    dp[0][0] = 0.0
    for k in range(1, L + 1):
        weight = 1.0 + 0.12 * (L - k)   # slack on early lines costs more
        for i in range(1, n + 1):
            best, bj = INF, -1
            for j in range(0, i):
                if dp[k - 1][j] == INF:
                    continue
                w = line_w(j, i)
                if w > max_w:
                    continue
                c = dp[k - 1][j] + weight * (max_w - w) ** 2
                if c < best:
                    best, bj = c, j
            dp[k][i] = best
            back[k][i] = bj
    if dp[L][n] == INF:
        return lines
    out = []
    i = n
    for k in range(L, 0, -1):
        j = back[k][i]
        out.append((j, i))
        i = j
    out.reverse()
    # never leave a lone short word on the last line if the greedy result avoided it
    if L >= 2:
        j, i = out[-1]
        if i - j == 1 and NBSP not in words[j] and line_w(j, i) < 0.22 * max_w and lines[-1][1] - lines[-1][0] > 1:
            return lines
    return out


NBSP = " "
NBHYPHEN = "‑"
# Brand phrases that never straddle a line break (glued with NBSP before wrapping). Authors can glue
# anything else, such as a number and its unit, by writing a non-breaking space (U+00A0) in the spec.
GLUE_PHRASES = ["ATR Lab", "ATR_Kent", "Kent State", "Kent Campus", "Physical AI", "World Robot Summit",
                "NASA SUITS"]
_GLUE_RES = [(re.compile(r"(?<!\w)" + re.escape(p) + r"(?!\w)"), p.replace(" ", NBSP)) for p in GLUE_PHRASES]
PLACEHOLDER_RE = re.compile(r"\[[^\[\]]*\]")
_AMPM_RE = re.compile(r"(\d)[ ](a\.m\.|p\.m\.|am|pm)(?!\w)")


def glue_phrases(text: str) -> str:
    """Replace the spaces inside brand phrases, inside a [bracketed placeholder] and between a number
    and a.m./p.m. with NBSP, so none of them straddles a line break (set_text falls back to word
    breaks for a glued phrase wider than 60 % of the measure, such as a whole placeholder quote)."""
    for rx, rep in _GLUE_RES:
        text = rx.sub(rep, text)
    text = PLACEHOLDER_RE.sub(lambda m: m.group(0).replace(" ", NBSP), text)
    return _AMPM_RE.sub(lambda m: m.group(1) + NBSP + m.group(2), text)


def set_text(style: Style, text: str, max_w: float, balance: bool = True) -> list:
    """Wrap text (hard newlines respected) into a list of line strings. Words are split on ASCII
    spaces only, so a non-breaking space (U+00A0) or non-breaking hyphen (U+2011) in the copy is
    honoured; brand phrases are glued automatically. A glued phrase wider than 60 % of the measure
    falls back to ordinary word breaks so it can never make the copy unfittable on its own."""
    ts = Typesetter(style)
    space = ts.width(" ")
    lines = []
    for para in text.replace("\r", "").split("\n"):
        words: list = []
        for w in re.split(r"[ \t]+", glue_phrases(para).strip()):
            if not w:
                continue
            if NBSP in w and ts.width(w) > 0.60 * max_w:
                words += w.split(NBSP)
            else:
                words.append(w)
        if not words:
            lines.append("")
            continue
        widths = [ts.width(w) for w in words]
        for j, i in wrap_paragraph(words, widths, space, max_w, balance):
            lines.append(" ".join(words[j:i]).replace(NBSP, " "))
    return lines


def wrap_segments(style: Style, segments: list, max_w: float) -> list:
    """Wrap a multi-segment eyebrow by whole segments: a line breaks only at a separator, and the
    separator is dropped at the break. Falls back to word wrapping when one segment alone is wider
    than the box."""
    ts = Typesetter(style)
    segs = [str(s).strip() for s in segments if str(s).strip()]
    lines: list = []
    cur: list = []
    for seg in segs:
        if cur and ts.width(SEP.join(cur + [seg])) > max_w:
            lines.append(SEP.join(cur))
            cur = [seg]
        else:
            cur.append(seg)
    if cur:
        lines.append(SEP.join(cur))
    if any(ts.width(ln) > max_w for ln in lines):
        return set_text(style, SEP.join(segs), max_w, balance=True)
    return lines


