def require_contrast(fg, bg, what: str, floor: float = 4.5):
    ratio = contrast(fg, bg)
    if ratio < floor:
        raise ContrastError(f"{what}: contrast {ratio:.2f}:1 is below the {floor}:1 floor "
                            f"(fg {fg} on bg {bg}); choose a token pair from the contrast matrix")
    return ratio


