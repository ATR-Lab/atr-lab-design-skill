class Ctx:
    """Per-render palette, sizes and helpers shared by the frame and the templates."""

    def __init__(self, spec: dict, size: SizeSpec, allow_placeholders: bool):
        self.spec, self.size, self.allow = spec, size, allow_placeholders
        self.staged = False      # set by render() when a cut-out stands on the stage (narrow rows column)
        s = size.scale
        self.s = s
        self.floor_any = self.px(FLOOR_ANY)
        self.bg = spec.get("background", "navy")
        self.navy_tile = self.bg == "navy"
        self.field = T.navy if self.navy_tile else T.gold
        # text colours per surface (all >= 4.5:1 against the field)
        if self.navy_tile:
            self.c_headline, self.c_body, self.c_eyebrow = T.white, T.white, T.gold
            self.c_secondary, self.c_accent = T.on_navy_secondary, T.gold
            self.c_plate, self.c_plate_glyph = T.gold, "navy"
            self.c_glyph = "white"
            self.c_bracket = T.navy300
        else:
            self.c_headline, self.c_body, self.c_eyebrow = T.navy, T.ink, T.navy
            self.c_secondary, self.c_accent = T.ink, T.navy
            self.c_plate, self.c_plate_glyph = T.navy, "gold"
            self.c_glyph = "navy"
            self.c_bracket = T.bronze
        for what, c in (("headline", self.c_headline), ("body", self.c_body), ("eyebrow", self.c_eyebrow),
                        ("secondary", self.c_secondary), ("accent", self.c_accent)):
            require_contrast(c, self.field, f"{what} on {self.bg}")

    def px(self, v: float) -> int:
        return int(round(v * self.s))

    def style(self, face_key: str, px: float, color: tuple, lh: float = 1.2, tracking: float = 0.0,
              upper: bool = False, align: str = "left") -> Style:
        """A Style at `px` (spec px at scale 1) scaled to this size; nothing may undercut the floor."""
        p = self.px(px)
        if p < self.floor_any:
            raise LayoutError(f"internal: {face_key} at {p} px is below the {self.floor_any} px floor for "
                              f"a {self.size.w} px wide tile")
        return Style(face_key, p, color, lh, tracking, upper, align, self.c_bracket if self.allow else None)

    def sizes(self, mx: float, mn: float, step: float) -> list:
        """Descending candidate sizes from mx to mn (spec px at scale 1), scaled."""
        out: list = []
        v = mx
        while v >= mn - 1e-6:
            p = self.px(v)
            if p not in out:
                out.append(p)
            v -= step
        p = self.px(mn)
        if p not in out:
            out.append(p)
        return out

    # -- common blocks (spec px at scale 1 = 1080 wide; floors from references/typography.md 4.4) ---
    def headline(self, text: str, mx=96, mn=FLOOR_HEADLINE, max_lines=4, face_key="sans-black", lh=1.04):
        st = self.style(face_key, mx, self.c_headline, lh=lh, tracking=-0.01)
        return TextBlock("title", text, st, self.sizes(mx, mn, 4), max_lines=max_lines, balance=True)

    def body(self, text, mx=44, mn=FLOOR_SUPPORT, max_lines=6, drop=0):
        if isinstance(text, list):
            st = self.style("sans", mx, self.c_body, lh=1.28)
            return GlyphRows("body", [str(t) for t in text], st, "tri", self.c_accent,
                             self.sizes(mx, mn, 2), row_gap_em=0.4, drop=drop)
        st = self.style("sans", mx, self.c_body, lh=1.3)
        return TextBlock("body", str(text), st, self.sizes(mx, mn, 2), max_lines=max_lines,
                         balance=False, drop=drop)

    def cta(self, text: str, drop: int = 0):
        st = self.style("sans-semibold", 40, self.c_headline, lh=1.22)
        return GlyphRows("cta", [text], st, "tri", self.c_accent, self.sizes(40, FLOOR_ANY, 2), drop=drop)

    def detail_rows(self, rows: list, mx: float = 40):
        """rows: list of (icon_name or None, text, max_lines); a date or time row is one line (it must not
        break), a place row may take two in the narrow column beside a staged cut-out. A None icon makes a
        continuation row (the time under its date) that keeps the text indent."""
        st = self.style("sans-semibold", mx, self.c_headline, lh=1.22)
        return GlyphRows("details", [t for _, t, _ in rows], st, "icon", self.c_accent,
                         self.sizes(mx, FLOOR_ANY, 2), row_gap_em=0.4, icons=[i for i, _, _ in rows],
                         icon_color=self.c_glyph, max_lines_per_row=[n for _, _, n in rows])

    def label(self, name: str, text: str, mx=48, mn=FLOOR_SUPPORT, max_lines=3, face_key="sans-semibold", drop=0):
        st = self.style(face_key, mx, self.c_headline, lh=1.18)
        return TextBlock(name, text, st, self.sizes(mx, mn, 2), max_lines=max_lines, balance=True, drop=drop)

    def mono(self, name: str, text: str, color=None, px=FLOOR_ANY, upper=False, drop=0):
        st = self.style("mono", px, color or self.c_accent, lh=1.3, upper=upper)
        return TextBlock(name, text, st, None, max_lines=2, balance=False, drop=drop)

    def secondary(self, name: str, text: str, px=FLOOR_ANY, max_lines=3, drop=0):
        st = self.style("sans", px, self.c_secondary, lh=1.3)
        return TextBlock(name, text, st, None, max_lines=max_lines, balance=False, drop=drop)

    def gap(self, v: float):
        return Gap(self.px(v))


# Blocks with drop > 0 may be dropped on 16:9 cards when nothing fits at the floors (higher first).
def _build_announcement(ctx: Ctx, sp: dict) -> list:
    blocks = [ctx.headline(sp["title"])]
    if sp.get("body"):
        blocks += [ctx.gap(28), ctx.body(sp["body"], drop=1)]
    if sp.get("cta"):
        blocks += [ctx.gap(40), ctx.cta(as_text(sp["cta"]))]
    return blocks


def _event_rows(ctx: "Ctx", sp: dict) -> list:
    rows = []
    if sp.get("date"):
        rows.append(("calendar-event", as_text(sp["date"]), 1))
    if sp.get("time"):
        rows.append(("calendar-event" if not sp.get("date") else None, as_text(sp["time"]), 1))
    if sp.get("place"):
        rows.append(("location", as_text(sp["place"]), 2 if ctx.staged else 1))
    return rows


def _build_event(ctx: Ctx, sp: dict) -> list:
    blocks = [ctx.headline(sp["title"], max_lines=3)]
    if sp.get("body"):
        blocks += [ctx.gap(24), ctx.body(sp["body"], max_lines=3, drop=1)]
    rows = _event_rows(ctx, sp)
    if rows:
        blocks += [ctx.gap(32), ctx.detail_rows(rows)]
    if sp.get("cta"):   # a 16:9 link card is its own call to action: the CTA row may drop there
        blocks += [ctx.gap(36), ctx.cta(as_text(sp["cta"]), drop=2 if ctx.size.hanging else 0)]
    return blocks


def _build_outreach(ctx: Ctx, sp: dict) -> list:
    """K-12 and community events: a bigger headline (112 px), the date, time and place rows at 44 px, the CTA.
    Gold field by default, with the concept illustration on the stage (references/social-media.md 7.5)."""
    wide = ctx.size.hanging     # 16:9 cards are short: the event template's gaps and row size
    blocks = [ctx.headline(sp["title"], mx=112, max_lines=3, lh=1.02)]
    if sp.get("body"):
        blocks += [ctx.gap(24), ctx.body(sp["body"], max_lines=3, drop=1)]
    rows = _event_rows(ctx, sp)
    if rows:
        blocks += [ctx.gap(32 if wide else 36), ctx.detail_rows(rows, mx=40 if wide else 44)]
    if sp.get("cta"):
        blocks += [ctx.gap(36 if wide else 40), ctx.cta(as_text(sp["cta"]), drop=2 if wide else 0)]
    return blocks


