@dataclass
class Placed:
    """A drawn text line or object, for the keep-out computation."""
    x0: float
    y0: float
    x1: float
    y1: float


class Block:
    fit_sizes: list = []          # descending candidate px sizes; [] = fixed
    max_lines: Optional[int] = None
    drop: int = 0                 # > 0: may be dropped on 16:9 cards when nothing fits (higher drops first)
    name = "block"
    narrow_w: Optional[float] = None   # stage layout: this block is set in the column beside the cut-out
    max_h: Optional[float] = None      # stage layout: the headline must end above the cut-out

    def set_px(self, px: int):
        pass

    def measure(self, width: float) -> float:
        raise NotImplementedError

    def lines_needed(self, width: float) -> int:
        return 1

    def lines_out(self, width: float) -> list:
        """The line strings as set (for meta and the wrapping tests)."""
        return []

    def problems(self, width: float) -> list:
        """Why this block does not fit at its current size (empty = it fits)."""
        out = []
        if self.max_lines is not None:
            n = self.lines_needed(width)
            if n > self.max_lines:
                out.append(f"{self.name} needs {n} lines (max {self.max_lines})")
        if self.max_h is not None and self.measure(width) > self.max_h:
            out.append(f"{self.name} is {self.measure(width):.0f} px tall but only {self.max_h:.0f} px fit above the illustration")
        return out

    def draw(self, canvas: Image.Image, x: float, y: float, width: float) -> list:
        raise NotImplementedError

    def _checked(self, placed: list, x: float, width: float) -> list:
        """Backstop: no drawn text may leave the column, whatever the fit logic decided."""
        for p in placed:
            over = p.x1 - (x + width)
            if over > 2:
                raise LayoutError(f"internal: {self.name} overflows the column by {over:.0f} px")
        return placed


class Gap(Block):
    name = "gap"

    def __init__(self, px: float):
        self.px = px

    def measure(self, width):
        return self.px

    def draw(self, canvas, x, y, width):
        return []


class TextBlock(Block):
    def __init__(self, name: str, text: str, style: Style, sizes: Optional[list] = None,
                 max_lines: Optional[int] = None, balance: bool = True, drop: int = 0):
        self.name, self.text, self.style = name, text, style
        self.fit_sizes = list(sizes or [])
        if self.fit_sizes:
            self.style = style.with_px(self.fit_sizes[0])
        self.max_lines, self.balance, self.drop = max_lines, balance, drop
        self._lines = None
        self._width = None
        self._overflow = None

    def set_px(self, px):
        self.style = self.style.with_px(px)
        self._lines = None

    def lines(self, width):
        if self._lines is None or self._width != width:
            try:
                self._lines = set_text(self.style, self.text, width, self.balance)
                self._overflow = None
            except LayoutError as exc:      # a word wider than the column: reported by problems(), so the
                self._lines = [self.text]   # fitter steps the size down before it gives up
                self._overflow = str(exc)
            self._width = width
        return self._lines

    def problems(self, width):
        self.lines(width)
        out = [f"{self.name}: {self._overflow}"] if self._overflow else []
        return out + super().problems(width)

    def lines_needed(self, width):
        return len(self.lines(width))

    def lines_out(self, width):
        return list(self.lines(width))

    def measure(self, width):
        n = len(self.lines(width))
        m = self.style.metrics
        return m["cap"] + (n - 1) * self.style.pitch + m["desc"]

    def draw(self, canvas, x, y, width):
        d = ImageDraw.Draw(canvas)
        ts = Typesetter(self.style)
        m = self.style.metrics
        base = y + m["cap"]
        out = []
        for line in self.lines(width):
            lw = ts.width(line)
            lx = x
            if self.style.align == "right":
                lx = x + width - lw
            elif self.style.align == "center":
                lx = x + (width - lw) / 2
            if line:
                ts.draw(d, lx, base, line)
                out.append(Placed(lx, base - m["cap"], lx + lw, base + m["desc"]))
            base += self.style.pitch
        return self._checked(out, x, width)


class GlyphRows(Block):
    """Rows of [glyph] text: bullets (triangle), CTA (triangle) or icon rows (asset icon)."""

    def __init__(self, name: str, items: list, style: Style, glyph: str, glyph_color: tuple,
                 sizes: Optional[list] = None, row_gap_em: float = 0.45, icons: Optional[list] = None,
                 icon_color: str = "white", max_lines_per_row: Optional[int] = None, drop: int = 0):
        self.name, self.items, self.style = name, items, style
        self.fit_sizes = list(sizes or [])
        if self.fit_sizes:
            self.style = style.with_px(self.fit_sizes[0])
        self.glyph, self.glyph_color, self.row_gap_em = glyph, glyph_color, row_gap_em
        self.icons, self.icon_color = icons, icon_color
        self.max_lines_per_row, self.drop = max_lines_per_row, drop
        self._cache = {}
        self._overflow = {}

    def set_px(self, px):
        self.style = self.style.with_px(px)
        self._cache = {}
        self._overflow = {}

    def _indent(self):
        px = self.style.px
        return int(round(px * (1.7 if self.glyph == "icon" else 0.95)))

    def _rows(self, width):
        key = (width, self.style.px)
        if key not in self._cache:
            w = width - self._indent()
            rows, overflow = [], []
            for t in self.items:
                try:
                    rows.append(set_text(self.style, t, w, balance=False))
                except LayoutError as exc:
                    rows.append([t])
                    overflow.append(f"{self.name}: {exc}")
            self._cache[key] = rows
            self._overflow[key] = overflow
        return self._cache[key]

    def lines_needed(self, width):
        return sum(len(r) for r in self._rows(width))

    def lines_out(self, width):
        return [ln for r in self._rows(width) for ln in r]

    def problems(self, width):
        self._rows(width)
        out = list(self._overflow.get((width, self.style.px), [])) + super().problems(width)
        if self.max_lines_per_row is not None:
            limits = (self.max_lines_per_row if isinstance(self.max_lines_per_row, list)
                      else [self.max_lines_per_row] * len(self.items))
            for item, rows, limit in zip(self.items, self._rows(width), limits):
                if len(rows) > limit:
                    out.append(f"{self.name} row '{item[:40]}' needs {len(rows)} lines (max {limit})")
        return out

    def measure(self, width):
        m, pitch = self.style.metrics, self.style.pitch
        gap = int(round(self.style.px * self.row_gap_em))
        h = 0
        for i, r in enumerate(self._rows(width)):
            h += m["cap"] + (len(r) - 1) * pitch + m["desc"]
            if i:
                h += gap
        return h

    def draw(self, canvas, x, y, width):
        d = ImageDraw.Draw(canvas)
        ts = Typesetter(self.style)
        m, pitch, px = self.style.metrics, self.style.pitch, self.style.px
        gap = int(round(px * self.row_gap_em))
        ind = self._indent()
        out = []
        cy = y
        for i, lines in enumerate(self._rows(width)):
            if i:
                cy += gap
            base = cy + m["cap"]
            xcenter = base - m["xh"] / 2
            if self.glyph == "icon":
                g = int(round(px * 1.3))
                if self.icons[i] is not None:  # None = a continuation row (the time under the date): text only
                    icon = scaled(str(icon_path(self.icons[i], self.icon_color)), g, g)
                    # icons carry 12 % padding: centre the box on the cap-height centre of the first line
                    paste(canvas, icon, x - g * 0.12, base - m["cap"] / 2 - g / 2)
                    out.append(Placed(x, base - m["cap"], x + g, base + m["desc"]))
            else:
                tri = px * 0.42
                triangle_right(canvas, x + px * 0.05, xcenter, tri, self.glyph_color)
            for line in lines:
                lw = ts.width(line)
                ts.draw(d, x + ind, base, line)
                out.append(Placed(x + ind, base - m["cap"], x + ind + lw, base + m["desc"]))
                base += pitch
            cy = base - pitch + m["desc"]
        return self._checked(out, x, width)


class Numeral(Block):
    """One-line big number (stat value) fitted to the column width. fit_stack steps it down to
    the floor when it is too wide, and fails loudly there."""

    max_lines = 1

    def __init__(self, name: str, text: str, style: Style, sizes: list):
        self.name, self.text, self.style = name, text, style.with_px(sizes[0])
        self.fit_sizes = list(sizes)

    def set_px(self, px):
        self.style = self.style.with_px(px)

    def lines_needed(self, width):
        return 1 if Typesetter(self.style).width(self.text) <= width else 2

    def lines_out(self, width):
        return [self.text]

    def problems(self, width):
        w = Typesetter(self.style).width(self.text)
        if w > width:
            return [f"{self.name} '{self.text}' is {w:.0f} px wide in a {width:.0f} px column"]
        return []

    def _extents(self) -> tuple:
        """(above, below): how far the actual glyphs reach above the baseline (brackets rise past
        the cap height) and below it (brackets, descenders)."""
        f = face(self.style.face).font(self.style.px)
        bb = f.getbbox(self.text, anchor="ls")
        return max(self.style.metrics["cap"], -bb[1]), max(0.0, bb[3])

    def measure(self, width):
        above, below = self._extents()
        return above + below

    def draw(self, canvas, x, y, width):
        d = ImageDraw.Draw(canvas)
        ts = Typesetter(self.style)
        above, below = self._extents()
        base = y + above
        w = ts.draw(d, x, base, self.text) - x
        return self._checked([Placed(x, y, x + w, base + below)], x, width)


@dataclass
class Stack:
    x: float
    width: float
    blocks: list

    def width_for(self, b: Block) -> float:
        """The measure a block is set in: the column, or the narrower column beside a staged cut-out."""
        return b.narrow_w if b.narrow_w else self.width


def fit_stack(stack: Stack, avail_h: float, label: str, allow_drop: bool = False) -> dict:
    """Shrink fit-able blocks in order (headline first) until the stack fits. On 16:9 cards
    (allow_drop) it then drops optional blocks, highest `drop` first, and refits from the maxima
    before it fails. Raises LayoutError with advice."""
    dropped: list = []
    while True:
        blocks = [b for b in stack.blocks if b.fit_sizes]
        idx = [0] * len(blocks)          # sequential shrinking: step the first block down, then the next
        problems: list = []
        while True:
            for b, i in zip(blocks, idx):
                b.set_px(b.fit_sizes[i])
            total = sum(b.measure(stack.width_for(b)) for b in stack.blocks)
            problems = [p for b in stack.blocks for p in b.problems(stack.width_for(b))]
            if total > avail_h:
                problems.append(f"content is {total:.0f} px tall but only {avail_h:.0f} px are available")
            if not problems:
                return {"height": total, "sizes": {b.name: b.style.px for b in blocks}, "dropped": dropped}
            stepped = False
            # a problem that belongs to one block (a row too wide, too many lines, a word wider than the
            # column) shrinks that block first, so a long date row never costs the headline its size
            if total <= avail_h:
                for k, b in enumerate(blocks):
                    if any(p.startswith(b.name) for p in problems) and idx[k] + 1 < len(b.fit_sizes):
                        idx[k] += 1
                        stepped = True
                        break
            if not stepped:
                for k in range(len(blocks)):
                    if idx[k] + 1 < len(blocks[k].fit_sizes):
                        idx[k] += 1
                        stepped = True
                        break
                    # this block is at its floor: keep it there and let the next one shrink
            if not stepped:
                break
        # nothing fits at the floors: on 16:9 cards drop the most optional block (and the gap before it)
        cands = [b for b in stack.blocks if b.drop > 0]
        if allow_drop and cands:
            victim = max(cands, key=lambda b: b.drop)
            i = stack.blocks.index(victim)
            del stack.blocks[i]
            if i > 0 and isinstance(stack.blocks[i - 1], Gap):
                del stack.blocks[i - 1]
            dropped.append(victim.name)
            continue
        sizes = ", ".join(f"{b.name} {b.fit_sizes[-1]} px" for b in blocks)
        if any(p.startswith("value") for p in problems):
            advice = ("Shorten the value (write 1.25M km rather than 1,250,000 km, or move the unit "
                      "into the label).")
        elif any(p.startswith("details row") for p in problems):
            advice = ("Keep each date, time and place row to one line: shorten the date (write 'July 13-17' "
                      "rather than the weekdays), give the time its own \"time\" row, shorten the place "
                      "('Kent Campus'), or move one of them into the post text.")
        elif any("above the illustration" in p for p in problems):
            advice = ("The headline must end above the cut-out: shorten it to three lines or fewer, or set "
                      "\"image_position\": \"top\" to put the illustration on its own panel.")
        elif allow_drop:
            advice = ("16:9 cards carry 3 to 5 words (references/social-media.md 5.2): shorten the title "
                      "and the rows, or render a square or portrait tile.")
        else:
            advice = "Shorten the copy (the title first), drop the body, or pick a taller size (portrait or story)."
        if dropped:
            advice += f" (Already dropped: {', '.join(dropped)}.)"
        raise LayoutError(f"{label}: cannot fit at the legibility floor ({sizes}): " + "; ".join(problems)
                          + ". " + advice)


