def triangle_right(canvas: Image.Image, x: float, cy: float, size: float, color: tuple):
    """Solid triangle, apex pointing right (the mark's roof turned 90 degrees): bullet / CTA glyph."""
    s = SS
    w, h = int(math.ceil(size * 1.2)) + 2, int(math.ceil(size)) + 2
    layer = Image.new("RGBA", (w * s, h * s), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    hh = size / 2
    pts = [(1 * s, 1 * s), (1 * s, (1 + size) * s), ((1 + size * 0.9) * s, (1 + hh) * s)]
    d.polygon(pts, fill=color + (255,))
    layer = layer.resize((w, h), Image.LANCZOS)
    paste(canvas, layer, x - 1, cy - hh - 1)


def hazard_band(canvas: Image.Image, kind: str, y: int, band_h: int):
    """Tile the measured hazard-stripe pattern across the full width at y."""
    tile = load_rgba(str(BANDS[kind]))
    tw = int(round(tile.width * band_h / tile.height))
    t = tile.resize((tw, band_h), Image.LANCZOS)
    strip = Image.new("RGBA", (canvas.width, band_h))
    x = 0
    while x < canvas.width:
        strip.alpha_composite(t, (x, 0))
        x += tw
    paste(canvas, strip, 0, y)


def fit_cover(im: Image.Image, w: int, h: int) -> Image.Image:
    r = max(w / im.width, h / im.height)
    nw, nh = int(math.ceil(im.width * r)), int(math.ceil(im.height * r))
    im = im.resize((nw, nh), Image.LANCZOS)
    x0, y0 = (nw - w) // 2, (nh - h) // 2
    return im.crop((x0, y0, x0 + w, y0 + h))


def fit_contain(im: Image.Image, w: int, h: int) -> Image.Image:
    r = min(w / im.width, h / im.height)
    return im.resize((max(1, int(im.width * r)), max(1, int(im.height * r))), Image.LANCZOS)


def with_alpha(im: Image.Image, alpha: float) -> Image.Image:
    a = im.getchannel("A").point(lambda v: int(v * alpha))
    out = im.copy()
    out.putalpha(a)
    return out


def ink_bbox(font: ImageFont.FreeTypeFont, text: str) -> tuple:
    """Tight ink bounding box of `text` relative to a left-baseline origin (x0, y0, x1, y1).
    Pillow's getbbox() clamps the bottom edge to the baseline, so it is wrong for glyphs that sit
    entirely above it (quotation marks); this renders a mask and measures the pixels."""
    asc, desc = font.getmetrics()
    w = int(math.ceil(font.getlength(text))) + 4
    mask = Image.new("L", (w + 8, asc + desc + 8), 0)
    ImageDraw.Draw(mask).text((4, asc + 4), text, font=font, fill=255, anchor="ls")
    bb = mask.getbbox()
    if bb is None:
        return (0, 0, 0, 0)
    return (bb[0] - 4, bb[1] - (asc + 4), bb[2] - 4, bb[3] - (asc + 4))


# --------------------------------------------------------------------------
# Lattice constellation (the ATR 60-degree geometry, seeded, never under text)
# --------------------------------------------------------------------------
def constellation(canvas: Image.Image, zone: tuple, color: tuple, accent: Optional[tuple],
                  seed: int, scale: float, corner: str = "top-right") -> Image.Image:
    """Draw outlined triangles, small filled triangles and a few lattice traces with square
    terminals inside `zone` (x0, y0, x1, y1). Returns the RGBA art layer (for the QA check)."""
    x0, y0, x1, y1 = zone
    S = 96.0 * scale
    HR = S * math.sqrt(3) / 2
    stroke = max(2.0, round(2.0 * scale * 2) / 2)
    inset = stroke * 1.5
    ax0, ay0, ax1, ay1 = x0 + inset, y0 + inset, x1 - inset, y1 - inset
    if ax1 - ax0 < 1.5 * S or ay1 - ay0 < 1.2 * HR:
        return Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    rnd = random.Random(seed)
    # lattice anchored at the zone's top-right corner so shapes sit flush with it
    ox, oy = ax1, ay0
    DIRS = [(S, 0), (S / 2, HR), (-S / 2, HR), (-S, 0), (-S / 2, -HR), (S / 2, -HR)]

    def vertex(i, j):
        return (ox - i * S - (S / 2 if j % 2 else 0.0), oy + j * HR)

    def allowed(p):
        return ax0 <= p[0] <= ax1 and ay0 <= p[1] <= ay1

    def add(p, d, k=1):
        return (p[0] + d[0] * k, p[1] + d[1] * k)

    cols = int((ax1 - ax0) / S) + 2
    rows = int((ay1 - ay0) / HR) + 2
    cand = [vertex(i, j) for j in range(rows) for i in range(cols) if allowed(vertex(i, j))]
    if not cand:
        return Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    zw, zh = ax1 - ax0, ay1 - ay0
    used_vertices: list = []

    def key(p):
        return (round(p[0]), round(p[1]))

    def pick():
        # grow a connected constellation: mostly start from a vertex that is already in use,
        # otherwise from a fresh vertex whose density falls off with distance from the corner
        if used_vertices and rnd.random() < 0.72:
            return rnd.choice(used_vertices)
        for _ in range(400):
            v = rnd.choice(cand)
            dx = (ax1 - v[0]) / zw
            dy = (v[1] - ay0) / zh if zh > 0 else 0
            dist = math.hypot(dx, dy) / math.sqrt(2)
            if rnd.random() < 0.25 + 0.75 * (1 - dist) ** 1.5:
                return v
        return rnd.choice(cand)

    def remember(pts):
        for p in pts:
            if key(p) not in {key(q) for q in used_vertices}:
                used_vertices.append(p)

    area = zw * zh / (S * HR)          # zone area in lattice cells
    n_outline = max(2, min(7, int(area / 4)))
    n_fill = max(1, min(3, int(area / 10)))
    n_trace = max(1, min(3, int(area / 12)))
    edges_used = set()
    polys_outline, polys_fill, traces, nodes = [], [], [], []

    def edge_key(a, b):
        return tuple(sorted(((round(a[0]), round(a[1])), (round(b[0]), round(b[1])))))

    tries = 0
    while len(polys_outline) < n_outline and tries < 300:
        tries += 1
        v = pick()
        k = rnd.choice([1, 1, 1, 2, 2])
        up = rnd.random() < 0.5
        pts = [v, add(v, DIRS[3], k), add(v, DIRS[4] if up else DIRS[2], k)]
        if not all(allowed(p) for p in pts):
            continue
        keys = [edge_key(pts[a], pts[b]) for a, b in ((0, 1), (1, 2), (2, 0))]
        if sum(kk in edges_used for kk in keys) > 1:
            continue
        edges_used.update(keys)
        polys_outline.append(pts)
        remember(pts)
    # traces: every trace leaves a vertex that a triangle already uses, turns at least once (no bare
    # bars, no lone diagonals) and runs 2 to 4 segments, so the cluster stays one composed object
    tries = 0
    while len(traces) < n_trace and tries < 200 and used_vertices:
        tries += 1
        p = rnd.choice(used_vertices)
        d = rnd.randrange(6)
        pts = [p]
        dirs: list = []
        for _ in range(rnd.randint(2, 4)):
            r = rnd.random()
            nd = d if (dirs and r < 0.45) else (d + 1) % 6 if r < 0.725 else (d - 1) % 6
            nxt = add(pts[-1], DIRS[nd])
            kk = edge_key(pts[-1], nxt)
            if not allowed(nxt) or kk in edges_used:
                break
            pts.append(nxt)
            dirs.append(nd)
            d = nd
        if len(pts) >= 3 and len(set(dirs)) >= 2:
            edges_used.update(edge_key(pts[i], pts[i + 1]) for i in range(len(pts) - 1))
            traces.append(pts)
            nodes += [pts[0], pts[-1]]
            remember(pts)
    # filled triangles sit inside an outlined one or share an edge with it (never float free)
    tries = 0
    fill_slots: set = set()
    while len(polys_fill) < n_fill and tries < 200 and polys_outline:
        tries += 1
        bi = rnd.randrange(len(polys_outline))
        base = polys_outline[bi]
        inside = rnd.random() < 0.5
        if inside:
            slot = (bi, "in")
            pts = list(base)
            sc = rnd.choice([0.42, 0.5, 0.5, 0.6])
        else:
            e = rnd.randrange(3)
            a, b, c = base[e], base[(e + 1) % 3], base[(e + 2) % 3]
            slot = (bi, e)
            pts = [a, b, (a[0] + b[0] - c[0], a[1] + b[1] - c[1])]    # reflected across the edge
            sc = 0.5
            if not all(allowed(p) for p in pts):
                continue
        if slot in fill_slots or (bi, "in") in fill_slots and inside:
            continue
        fill_slots.add(slot)
        cx = sum(p[0] for p in pts) / 3
        cy = sum(p[1] for p in pts) / 3
        polys_fill.append([(cx + (p[0] - cx) * sc, cy + (p[1] - cy) * sc) for p in pts])

    # render at SSx inside the zone's bbox
    bx0, by0 = int(math.floor(x0)), int(math.floor(y0))
    bw, bh = int(math.ceil(x1)) - bx0, int(math.ceil(y1)) - by0
    layer = Image.new("RGBA", (bw * SS, bh * SS), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)

    def P(p):
        return ((p[0] - bx0) * SS, (p[1] - by0) * SS)

    sw = int(round(stroke * SS))
    for idx, pts in enumerate(polys_outline):
        col = accent if (accent and idx == len(polys_outline) - 1 and len(polys_outline) > 2) else color
        d.polygon([P(p) for p in pts], outline=col + (255,), width=sw)
    for idx, pts in enumerate(traces):
        col = accent if (accent and idx == 0 and len(traces) > 1) else color
        d.line([P(p) for p in pts], fill=col + (255,), width=sw, joint="curve")
    node = max(6.0, 8.0 * scale)
    for p in nodes:
        q = P(p)
        r = node * SS / 2
        d.rectangle([q[0] - r, q[1] - r, q[0] + r, q[1] + r], fill=color + (255,))
    for pts in polys_fill:
        d.polygon([P(p) for p in pts], fill=color + (255,))
    small = layer.resize((bw, bh), Image.LANCZOS)
    art = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    art.alpha_composite(small, (bx0, by0))
    canvas.alpha_composite(art)
    return art


