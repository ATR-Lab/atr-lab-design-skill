def _seed(spec: dict, size: SizeSpec) -> int:
    h = hashlib.sha1(f"{spec.get('template')}|{spec.get('title', '')}|{size.name}".encode()).hexdigest()
    return int(h[:12], 16)


# Copy checks (references/brand-foundation.md 11-12 facts and Kent State editorial style; brand_check.py
# applies the same rules as its `wording` check).
BANNED_COPY = [
    (re.compile(r"@atr_kent(?!\w)", re.I), "the handle @atr_kent does not exist; the lab's X handle is @atrlab_kent"),
    (re.compile(r"\bRoom 236\b"), "Room 236 is not a verified lab address; write a [Room] placeholder or the department address"),
    (re.compile(r"330-672-9060"), "330-672-9060 is not a verified lab number; write a placeholder or the department's 330-672-9980"),
    (re.compile(r"College\s+of\s+Arts\s+(?:and|&)\s+Sciences", re.I),
     "wrong college: Computer Science is in the College of Sciences and Humanities"),
    (re.compile(r"\bMath(?:ematics)?\s+(?:and|&)\s+Computer\s+Science\s+Building\b", re.I),
     "older building name: write 'Mathematical Sciences Building'"),
]
SOFT_COPY = [
    (re.compile(r"\s&\s"), "write 'and' rather than '&' (Kent State editorial style)"),
    (re.compile(r",\s+(and|or)\s", re.I), "probable Oxford comma; Kent State style omits it"),
    (re.compile(r"\bKSU\b"), "avoid 'KSU' in running copy; write Kent State"),
]
COPY_SKIP = {"image", "alt_text", "image_alt", "template", "size", "background", "icon", "art", "signature",
             "safe", "image_position"}


def copy_strings(obj, path: str = "spec") -> list:
    """Every copy string in the spec as (path, text), skipping paths and settings."""
    out = []
    if isinstance(obj, str):
        out.append((path, obj))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            out += copy_strings(v, f"{path}[{i}]")
    elif isinstance(obj, dict):
        for k, v in obj.items():
            if k not in COPY_SKIP:
                out += copy_strings(v, f"{path}.{k}")
    return out


def check_copy(spec: dict) -> tuple:
    """(errors, notes): errors are refused facts, notes are style warnings."""
    errors, notes = [], []
    for path, text in copy_strings(spec):
        for rx, msg in BANNED_COPY:
            if rx.search(text):
                errors.append(f"{path}: {msg}")
        for rx, msg in SOFT_COPY:
            if rx.search(text):
                notes.append(f"{path}: {msg}")
    return errors, notes


def resolve_spec_path(path: str, base_dir: Optional[Path] = None) -> Optional[Path]:
    """Resolve a file named in a spec ("image"). An absolute path is used as is; a relative path is tried
    against the current directory, then the spec file's own folder, then the skill root, so the shipped
    examples can say `assets/illustrations/...` and work from anywhere. None when nothing exists."""
    p = Path(path).expanduser()
    if p.is_absolute():
        return p if p.exists() else None
    bases = [Path.cwd()] + ([Path(base_dir)] if base_dir else []) + [HERE.parent]
    for base in bases:
        cand = (base / p)
        if cand.exists():
            return cand.resolve()
    return None


def validate_spec(spec: dict, size_name: Optional[str] = None, allow_placeholders: bool = False,
                  base_dir: Optional[Path] = None) -> tuple:
    if not isinstance(spec, dict):
        raise SpecError("spec must be a JSON object")
    tname = spec.get("template")
    if tname not in TEMPLATES:
        raise SpecError(f"unknown template '{tname}'; choose one of: {', '.join(TEMPLATES)}")
    tpl = TEMPLATES[tname]
    sname = size_name or spec.get("size") or tpl.default_size
    if sname not in SIZES:
        raise SpecError(f"unknown size '{sname}'; choose one of: {', '.join(SIZES)}")
    bg = spec.get("background") or tpl.default_background
    if bg not in ("navy", "gold"):
        raise SpecError(f"background must be 'navy' or 'gold' (got '{bg}'); colors come from the token file only")
    art = spec.get("art", "lattice")
    if art not in ("lattice", "ghost", "none"):
        raise SpecError("art must be 'lattice', 'ghost' or 'none'")
    if spec.get("signature", "mark") not in ("mark", "lockup"):
        raise SpecError("signature must be 'mark' (default) or 'lockup'")
    if spec.get("safe", "reel") not in STORY_SAFE:
        raise SpecError(f"safe must be one of: {', '.join(STORY_SAFE)} (story size only)")
    if tname not in ("stat", "quote") and not str(spec.get("title", "")).strip():
        raise SpecError("'title' is required")
    if tname == "stat" and not as_text(spec.get("value") or "").strip():
        raise SpecError("stat: 'value' is required (e.g. \"44%\")")
    if tname == "quote" and not as_text(spec.get("quote") or spec.get("title") or "").strip():
        raise SpecError("quote: 'quote' (or 'title') is required")
    icon = spec.get("icon", tpl.default_icon)
    if icon:
        icon_path(icon, "navy")
    if spec.get("image"):
        p = resolve_spec_path(spec["image"], base_dir)
        if p is None:
            raise SpecError(f"image not found: {spec['image']} (looked in the current directory, the spec's folder "
                            f"and the skill root {HERE.parent})")
    if spec.get("image_position", "auto") not in ("auto", "stage", "top", "right"):
        raise SpecError("image_position must be 'auto', 'stage', 'top' or 'right'")
    errors, _ = check_copy(spec)
    if errors:
        raise SpecError("refused copy (references/brand-foundation.md 11):\n  " + "\n  ".join(errors))
    if not allow_placeholders:
        ph = find_placeholders(spec)
        if ph:
            raise PlaceholderError("placeholder text found; replace it or pass --allow-placeholders:\n  "
                                   + "\n  ".join(ph))
    known = {"template", "size", "background", "eyebrow", "title", "body", "date", "time", "place", "cta", "icon",
             "number", "art", "signature", "safe", "image", "image_position", "image_alt", "alt_text",
             "authors", "venue", "link", "value", "label", "source", "quote", "attribution", "role", "tag"}
    unknown = sorted(set(spec) - known)
    return tpl, size_for(sname, spec), bg, unknown


ALT_ACRONYMS = {"AI", "VR", "AR", "XR", "UAV", "UAS", "NASA", "SUITS", "ATR", "STEM", "PI", "DOI", "EP",
                "IEEE", "ACM", "HRI", "ICRA", "IROS", "RSS", "ROS", "US", "USA", "OH", "NSF", "CS", "WRS",
                "REU", "TV", "Q&A", "FAQ", "RSVP"}
# Degrees in AP style (references/voice-and-copy.md §3): PHD / PH.D. -> Ph.D., MS / M.S. -> M.S., BS / B.S. -> B.S.
ALT_DEGREES = {"PHD": "Ph.D.", "MS": "M.S.", "BS": "B.S."}
ALT_SMALL = {"a", "an", "the", "of", "and", "or", "at", "in", "on", "for", "to", "from", "with", "by"}
_ALT_PUNCT = "[](),.:;!?"


def _alt_degree(word: str) -> Optional[str]:
    """AP spelling of a degree word ('PH.D.', 'PHD,', 'M.S./PH.D.'), keeping the surrounding punctuation;
    None if the word is not a degree."""
    core = word.strip(_ALT_PUNCT)
    parts = core.split("/")
    if not core or any(p.replace(".", "") not in ALT_DEGREES for p in parts):
        return None
    lead = word[:len(word) - len(word.lstrip(_ALT_PUNCT))]
    tail = word[len(word.rstrip(_ALT_PUNCT)):]
    ap = "/".join(ALT_DEGREES[p.replace(".", "")] for p in parts)
    if tail.startswith("."):  # the abbreviation's own period ends the word or sentence: print it once
        tail = tail[1:]
    return lead + ap + tail


def eyebrow_for_alt(text: str) -> str:
    """An all-caps eyebrow read aloud is shouted letter by letter by some screen readers: give the
    alt text a title-cased copy, keeping acronyms and anything with a digit. Mixed case is kept."""
    if text != text.upper():
        return text
    words = text.split(" ")
    out = []
    for i, w in enumerate(words):
        core = w.strip(_ALT_PUNCT)
        degree = _alt_degree(w)
        if not core:
            out.append(w)
        elif degree:
            out.append(degree)
        elif core in ALT_ACRONYMS or core.replace(".", "") in ALT_ACRONYMS or any(ch.isdigit() for ch in core):
            out.append(w)          # acronyms, dotted ones such as U.S., and anything with a digit stay as written
        elif core.lower() in ALT_SMALL and i > 0 and words[i - 1] not in ("", "·"):
            out.append(w.lower())
        else:
            j = 1 if w.startswith("[") else 0
            out.append(w[:j + 1] + w[j + 1:].lower())
    return " ".join(out)


def compose_alt(spec: dict, tpl: Template) -> str:
    """The alt text composed from the copy: the key message first (the headline, the number, the quote), then who
    is speaking, then the eyebrow and every detail row, then the image. Screen readers and platform previews
    read the start first, so the key message sits inside the first ~100 characters; no platform limit is
    assumed, and because the caption repeats the details a concise alt text is acceptable."""
    lead = {"announcement": "Announcement", "event": "Event announcement", "outreach": "Event announcement",
            "publication": "New publication", "recruiting": "Recruiting graphic", "stat": "Statistic graphic",
            "quote": "Quote graphic", "video-cover": "Video cover", "welcome": "Welcome graphic"}[tpl.name]
    who = f"{lead} from the Advanced Telerobotics Research Lab at Kent State University."
    if tpl.name == "stat":
        key = f"{as_text(spec.get('value'))} {as_text(spec.get('label') or spec.get('title'))}".strip().rstrip(".") + "."
    elif tpl.name == "quote":
        key = "Quote: \u201c" + as_text(spec.get("quote") or spec.get("title")).strip() + "\u201d"
    else:
        key = str(spec.get("title", "")).strip().rstrip(".") + "."
    parts = [key, who]
    if tpl.name == "quote" and spec.get("attribution"):
        parts.append(as_text(spec["attribution"]) + (", " + as_text(spec["role"]) if spec.get("role") else "") + ".")
    if spec.get("eyebrow"):
        parts.append(eyebrow_for_alt(as_text(spec["eyebrow"]).strip()).rstrip(".") + ".")
    body = spec.get("body")
    if body:
        parts.append(("; ".join(str(b) for b in body) if isinstance(body, list) else str(body)).strip().rstrip(".") + ".")
    for k in ("authors", "venue", "date", "time", "place", "link", "source", "cta"):
        if spec.get(k):
            parts.append(as_text(spec[k]).strip().rstrip(".") + ".")
    if spec.get("image_alt"):
        ia = str(spec["image_alt"]).strip().rstrip(".") + "."
        if not re.match(r"(illustration|concept|photo|picture|drawing|diagram)", ia, re.I):
            ia = "Image: " + ia
        parts.append(ia)
    text = " ".join(p for p in parts if p and p != ".")
    return re.sub(r"\s+", " ", text).strip()


ALT_LEAD_CHARS = 100  # the key message should start within this many characters (no platform limit is assumed)


def alt_lead_note(alt: str, spec: dict, tpl: Template) -> Optional[str]:
    """A warning when the card's key message first appears after ALT_LEAD_CHARS characters."""
    key = as_text(spec.get("value") if tpl.name == "stat" else spec.get("quote") or spec.get("title") or "")
    key = re.sub(r"\s+", " ", key).strip()[:24].lower()
    if not key:
        return None
    pos = alt.lower().find(key)
    if pos < 0 or pos > ALT_LEAD_CHARS:
        return (f"alt text: the key message first appears at character {pos if pos >= 0 else '?'}; put it in the "
                f"first ~{ALT_LEAD_CHARS} characters (the full text equivalent may follow)")
    return None


def render(spec: dict, size: Optional[str] = None, allow_placeholders: bool = False,
           safe_zones: bool = False, base_dir: Optional[Path] = None) -> tuple:
    """Render one tile. Returns (PIL.Image RGB, meta dict). `base_dir` is the spec file's folder, one of
    the places a relative "image" path is looked up (see resolve_spec_path)."""
    tpl, sz, bg, unknown = validate_spec(spec, size, allow_placeholders, base_dir)
    sp = dict(spec)
    sp["background"] = bg
    ctx = Ctx(sp, sz, allow_placeholders)
    s = ctx.s
    W, H, m = sz.w, sz.h, sz.margin
    navy = ctx.navy_tile
    hanging = sz.hanging
    meta = {"template": tpl.name, "size": sz.name, "px": [W, H], "background": bg, "warnings": []}
    if unknown:
        meta["warnings"].append(f"ignored unknown fields: {', '.join(unknown)}")
    meta["warnings"] += check_copy(sp)[1]

    canvas = Image.new("RGBA", (W, H), ctx.field + (255,))
    draw = ImageDraw.Draw(canvas)
    clear = ctx.px(48)

    # -- fixed geometry ------------------------------------------------------
    short = min(W, H)
    band_h = int(round(0.0667 * short))
    band_clear = int(round(0.053 * short))
    band_y = H - band_h if navy else 0
    # the field the layout may use: outside the band (+ its clear zone) and outside platform UI
    band_top = band_h + band_clear if not navy else 0
    band_bot = band_h + band_clear if navy else 0
    top_edge = max(sz.ui_top, band_top)
    bottom_edge = min(H - sz.ui_bottom, H - band_bot)
    # inset from that field: the margin at a tile edge, a smaller inset inside a platform safe box
    # (the safe box is already the visible area), the band clear zone next to a band
    mv = min(m, int(round(0.09 * H))) if hanging else m      # vertical margin: 9 % of a 16:9 card's height
    ui_inset = ctx.px(40)
    in_ui_top = bool(sz.ui_top) and top_edge == sz.ui_top
    in_ui_bottom = bool(sz.ui_bottom) and bottom_edge == H - sz.ui_bottom
    if in_ui_top:
        header_y = top_edge + ui_inset
    else:
        header_y = top_edge + (max(mv, band_clear) - band_clear if band_top else mv)
    if in_ui_bottom:
        sig_bottom = bottom_edge - ui_inset
    else:
        sig_bottom = bottom_edge - (0 if band_bot else mv)

    # -- image: decided first, because a staged cut-out changes the signature colour and positions ----
    image = None
    img_rect = None
    stage = None
    img_pos = sp.get("image_position", "auto")
    if sp.get("image"):
        image = load_rgba(str(resolve_spec_path(sp["image"], base_dir)))
        has_alpha = image.getchannel("A").getextrema()[0] < 255
        if img_pos == "auto":
            img_pos = "stage" if has_alpha else ("right" if hanging else "top")
        if img_pos == "stage" and not has_alpha:
            raise SpecError("image_position 'stage' needs a transparent cut-out (a PNG with alpha) such as the concept "
                            "illustrations in assets/illustrations; a photo takes 'top' or 'right'")
    staged = image is not None and img_pos == "stage"
    mark_on_panel = staged and not hanging      # 16:9 cards get a pedestal under the cut-out, not a full stage

    # -- signatures: sizes now, drawn last -------------------------------------------
    # Two separate signatures at equal height, bottoms aligned (logos/README.md section 7): the ATR
    # mark bottom-left (references/social-media.md 5.3: 120-130 px on a 1080 px tile) and the Kent
    # State wordmark bottom-right, white on navy. Gold tiles carry a navy text credit instead. On the
    # white stage panel the mark is navy, the wordmark moves to the top right and the credit sits
    # beside the mark.
    sig_mode = sp.get("signature", "mark")
    if sig_mode == "mark":
        atr_key = "mark-gold" if (navy and not mark_on_panel) else "mark-navy"
        atr_h = int(round((0.0833 if hanging else 0.12) * W))
        atr_w = int(round(atr_h * aspect(LOGOS[atr_key])))
        atr_clear = 0.328 * atr_h                     # clear space X = roof height
        size_ok = atr_h >= MARK_MIN_PX
    else:
        atr_key = "atr-short-reverse" if (navy and not mark_on_panel) else "atr-short-navy"
        asp = aspect(LOGOS[atr_key])
        atr_w = int(round(min(0.333 * W, (0.36 if hanging else 0.42) * H)))
        if navy:   # the wordmark at the lockup's height must stay >= KSU_MIN_PX wide
            atr_w = max(atr_w, int(math.ceil(KSU_MIN_PX / aspect(LOGOS["ksu-white"]) * asp)))
        atr_h = int(round(atr_w / asp))
        atr_clear = 0.329 * atr_h
        size_ok = atr_w >= LOCKUP_MIN_PX
        meta["warnings"].append("signature 'lockup': the lockup's lettering falls below 8 px when a phone shows the "
                                "card at a third of its size; use it for cards viewed at full size "
                                "(references/social-media.md 5.3)")
    kw = kh = 0
    if navy:
        kh = atr_h
        kw = int(round(kh * aspect(LOGOS["ksu-white"])))
    if not size_ok or (navy and kw < KSU_MIN_PX):
        raise LayoutError(f"internal: signature below minimum size (ATR {atr_w}x{atr_h} px, wordmark {kw} px wide)")
    # YouTube's duration badge owns the bottom-right corner: on youtube-thumb the wordmark moves to
    # the top-right of the header row, and the text credit on gold stays right-aligned to the badge
    # column's left edge (x < 1100 at 1280 wide)
    ksu_top_right = navy and (sz.name == "youtube-thumb" or staged)
    credit_right = W - m
    if sz.name == "youtube-thumb":
        credit_right = min(credit_right, int(YT_BADGE[0] * W / 1280.0) - clear)
    credit_st = None
    credit_lines: list = []
    credit_w = credit_h = 0
    if not navy:
        # gold tiles carry no wordmark (white fails 2.0:1, the colour file's sunburst vanishes): a
        # two-line navy credit names the lab and Kent State (references/social-media.md 5.3). On a
        # staged card it moves to the top right of the header row, in three shorter lines, where the
        # wordmark goes on navy, because the cut-out owns the bottom right.
        credit_st = ctx.style("sans-semibold", FLOOR_ANY, T.navy, lh=1.25, align="right")
        credit_lines = (["Advanced Telerobotics", "Research Lab", "Kent State University"] if staged
                        else ["Advanced Telerobotics Research Lab", "Kent State University"])
        cts = Typesetter(credit_st)
        credit_w = int(math.ceil(max(cts.width(ln) for ln in credit_lines)))
        credit_h = credit_st.metrics["cap"] + (len(credit_lines) - 1) * credit_st.pitch
    credit_top_right = (not navy) and staged
    sig_top = sig_bottom - atr_h
    # clear space above the signatures: 1 X for the mark or lockup, the K height for the wordmark
    # (the KENT line is 0.305 of the file height), never less than a block gap
    sig_gap = max(ctx.px(40), int(round(atr_clear)),
                  int(round(KSU_K_HEIGHT * kh)) if (navy and not ksu_top_right) else 0)
    content_bottom = sig_top - sig_gap

    # -- image panel (optional) ------------------------------------------------------
    # "stage" = a transparent cut-out standing bottom-right on a white panel, rising into the field
    # (default for cut-outs); "top" = a band across the top (default for photos on stacked tiles, so the
    # copy keeps the full width); "right" = a column from the top edge to the signature row (default for
    # photos on 16:9 cards)
    if staged:
        cut = image.crop(image.getbbox())
        top_sig_h = kh if navy else credit_h          # the Kent State signature sits top right on a staged card
        if hanging:
            # the cut-out spans most of the height, but starts below the header signature's clear space
            ill_h = min(int(round(0.60 * H)), sig_bottom - (header_y + top_sig_h + clear))
            max_w = int(round(0.36 * W))
        else:
            ill_h, max_w = int(round(min(0.40 * W, 0.40 * (sig_bottom - header_y)))), int(round(0.44 * W))
        ill_w = int(round(ill_h * cut.width / cut.height))
        if ill_w > max_w:
            ill_w, ill_h = max_w, int(round(max_w * cut.height / cut.width))
        ill_x1, ill_y1 = W - m, sig_bottom              # its feet on the signatures' baseline
        if sz.name == "youtube-thumb" and ill_y1 > YT_BADGE[1] * H / 720.0:   # gold: no band lifts the feet
            ill_x1 = min(ill_x1, int(YT_BADGE[0] * W / 1280.0) - clear)          # so stay left of the badge column
        ill_x0, ill_y0 = ill_x1 - ill_w, ill_y1 - ill_h
        # Stacked tiles: the white stage spans the width, holds the signatures with their clear space and
        # the lower 45 % of the cut-out, and the rest rises into the field; it runs to the band (navy), the
        # tile edge (gold) or the safe box, and the text ends above it. 16:9 cards: a pedestal under the
        # cut-out only, so the text column keeps its full height beside it.
        panel_bottom = bottom_edge if in_ui_bottom else (band_y if navy else H)
        if hanging:
            panel = (ill_x0 - clear, ill_y0 + int(round(0.55 * ill_h)), W, panel_bottom)
        else:
            panel_top = min(content_bottom, ill_y0 + int(round(0.55 * ill_h)))
            panel = (0, panel_top, W, panel_bottom)
            content_bottom = panel_top
        stage = {"cut": cut, "rect": (ill_x0, ill_y0, ill_x1, ill_y1), "panel": panel,
                 "narrow_right": ill_x0 - clear}
    elif image is not None:
        img_y0 = 0 if navy else band_h + band_clear     # bleed to the top edge (under a story's UI)
        if img_pos == "right":
            iw = int(round((0.42 if hanging else 0.44) * W))
            img_rect = (W - iw, img_y0, W, sig_top - ctx.px(40))
        else:
            img_y1 = top_edge + int(round((0.26 if sz.ui_top else 0.30) * (bottom_edge - top_edge)))
            img_rect = (0, img_y0, W, img_y1)
            header_y = img_y1 + clear
    meta["image_position"] = img_pos if image is not None else None
    ksu_shown = navy
    if ksu_top_right and img_rect and img_pos == "right":
        ksu_shown = False        # the wordmark needs a plain area, and the photo owns the right of a thumbnail
        meta["warnings"].append("Kent State wordmark omitted: a youtube-thumb with a photo at the right has no plain "
                                "corner for it (name Kent State in the video title or description)")

    # -- header row: plate + eyebrow (+ tag; + the wordmark top-right on youtube-thumb and staged navy tiles)
    P = ctx.px(100 if hanging else (120 if (image is not None and not staged) else 160))
    plate_x, plate_y = m, header_y
    icon = sp.get("icon", tpl.default_icon)
    number = as_text(sp.get("number") or "")
    is_video = tpl.name == "video-cover"
    has_plate = (bool(icon) or bool(number) or tpl.name == "quote") and not is_video
    right_limit = W - m
    ksu_rect = None
    credit_rect = None
    if ksu_shown and ksu_top_right:
        ky = header_y + (P - kh) // 2 if (staged and not hanging and has_plate) else header_y  # centred on the plate
        ksu_rect = (W - m - kw, ky, W - m, ky + kh)
        right_limit = ksu_rect[0] - clear
    elif credit_top_right:
        cy = header_y + (P - credit_h) // 2 if (not hanging and has_plate) else header_y
        credit_rect = (W - m - credit_w, cy, W - m, cy + credit_h)
        right_limit = credit_rect[0] - clear
    col_x = m
    if has_plate and hanging:
        col_x = plate_x + P + ctx.px(24)
    art_mode = "none" if (image is not None or is_video) else sp.get("art", "lattice")
    text_right = right_limit
    if img_rect and img_pos == "right":
        text_right = img_rect[0] - ctx.px(56)
    if staged:
        # stacked: the headline runs full width above the cut-out and only the eyebrow stops before the
        # wordmark; 16:9: the whole column sits beside the cut-out
        text_right = stage["narrow_right"] if hanging else W - m
    if art_mode == "ghost":
        text_right = min(text_right, int(0.60 * W))    # the ghost mark starts at 64 % of the width
    col_w = text_right - col_x
    eyebrow_raw = sp.get("eyebrow") or ""
    eyebrow_text = as_text(eyebrow_raw)
    eyebrow_style = ctx.style("sans-semibold", FLOOR_ANY, ctx.c_eyebrow, lh=1.25, tracking=0.08, upper=True)
    ebm = eyebrow_style.metrics
    eb_x = (plate_x + P + ctx.px(24 if hanging else 32)) if has_plate else col_x
    tag_text = as_text(sp.get("tag") or "") if is_video else ""
    tag_style = ctx.style("mono-semibold", FLOOR_ANY, ctx.c_eyebrow, lh=1.2, upper=True)
    tag_w = Typesetter(tag_style).width(tag_text) if tag_text else 0
    tag_x = text_right - tag_w
    eb_right = (tag_x - clear) if tag_text else min(text_right, right_limit)
    eb_w = eb_right - eb_x

    # -- video-cover: big plate at right carries the icon; no header plate ----------
    big_plate = None
    if is_video:
        zone_top = header_y + ebm["cap"] + ctx.px(28)
        if ksu_rect:
            zone_top = max(zone_top, ksu_rect[3] + clear)
        side = min(content_bottom - zone_top, int(round(0.34 * W)))
        side = max(side, ctx.px(200))
        big_plate = (text_right - side, zone_top + ((content_bottom - zone_top) - side) // 2, side)
        col_w = big_plate[0] - clear - col_x
    if not eyebrow_text:
        eb_lines = []
    elif isinstance(eyebrow_raw, list) and len(eyebrow_raw) > 1:
        eb_lines = wrap_segments(eyebrow_style, eyebrow_raw, eb_w)     # break only at a separator
    else:
        eb_lines = set_text(eyebrow_style, eyebrow_text, eb_w, balance=True)
    if len(eb_lines) > 2:
        raise LayoutError(f"eyebrow needs {len(eb_lines)} lines in {eb_w:.0f} px; keep it to two lines or shorten it")
    eb_h = ebm["cap"] + (len(eb_lines) - 1) * eyebrow_style.pitch if eb_lines else 0
    if has_plate and not hanging:
        header_h, gap_after_header = P, ctx.px(44)
    else:
        header_h, gap_after_header = eb_h, ctx.px(28)
    content_top = header_y + header_h + gap_after_header

    def eyebrow_baseline() -> float:
        """Baseline of the first eyebrow line: centred on a stacked plate, top-aligned beside a hanging one."""
        if has_plate and not hanging:
            b = plate_y + P / 2 + ebm["cap"] / 2
            return b - eyebrow_style.pitch / 2 if len(eb_lines) == 2 else b
        if has_plate and hanging:
            return plate_y + ctx.px(8) + ebm["cap"]
        return header_y + ebm["cap"]

    # -- content stack ----------------------------------------------------------
    ctx.staged = staged
    blocks = tpl.build(ctx, sp)
    if staged and not hanging:
        # the headline keeps the full width but must end above the cut-out; everything under it is set in
        # the column beside the cut-out
        narrow_w = stage["narrow_right"] - col_x
        for b in blocks:
            if b.name == "title":
                b.max_h = (stage["rect"][1] - clear) - content_top
            elif not isinstance(b, Gap):
                b.narrow_w = narrow_w
    stack = Stack(col_x, col_w, blocks)
    avail = content_bottom - content_top
    fit = fit_stack(stack, avail, f"{tpl.name}/{sz.name}", allow_drop=hanging)
    meta["fit"] = fit["sizes"]
    meta["dropped"] = fit["dropped"]
    if fit["dropped"]:
        meta["warnings"].append(f"dropped {', '.join(fit['dropped'])}: 16:9 cards carry 3 to 5 words "
                                "(references/social-media.md 5.2); shorten the copy or use a portrait (4:5) or "
                                "square size to keep it")
    meta["lines"] = {"eyebrow": list(eb_lines)}
    for b in stack.blocks:
        if not isinstance(b, Gap):
            meta["lines"][b.name] = b.lines_out(stack.width_for(b))
    group_h = header_h + gap_after_header + fit["height"]
    y_offset = 0
    if sz.valign == "middle" and not staged:   # a staged card is top-anchored: the cut-out defines the bottom
        free = (content_bottom - header_y) - group_h
        if free > 0:
            y_offset = int(free * 0.42)   # optical centre sits a little above the geometric one
    plate_y += y_offset
    header_y += y_offset
    content_top += y_offset
    if ksu_rect:
        ksu_rect = (ksu_rect[0], ksu_rect[1] + y_offset, ksu_rect[2], ksu_rect[3] + y_offset)
    if big_plate:
        big_plate = (big_plate[0], big_plate[1] + y_offset, big_plate[2])

    # -- pre-compute occupied rects to place the art ------------------------------
    # Draw text onto a scratch copy first to learn the exact extents, then draw art on the
    # real canvas, then the text again on top (cheap: a tile takes well under a second).
    scratch = canvas.copy()
    header_rects = []
    if has_plate:
        header_rects.append(Placed(plate_x, plate_y, plate_x + P, plate_y + P))
    if eb_lines:
        base = eyebrow_baseline()
        ts = Typesetter(eyebrow_style)
        for line in eb_lines:
            header_rects.append(Placed(eb_x, base - ebm["cap"], eb_x + ts.width(line), base))
            base += eyebrow_style.pitch
    if tag_text:
        header_rects.append(Placed(tag_x, eyebrow_baseline() - ebm["cap"], tag_x + tag_w, eyebrow_baseline()))
    if ksu_rect:
        header_rects.append(Placed(*ksu_rect))
    if credit_rect:
        header_rects.append(Placed(*credit_rect))
    if big_plate:
        header_rects.append(Placed(big_plate[0], big_plate[1], big_plate[0] + big_plate[2], big_plate[1] + big_plate[2]))
    placed = list(header_rects)
    y = content_top
    for b in stack.blocks:
        placed += b.draw(scratch, stack.x, y, stack.width_for(b))
        y += b.measure(stack.width_for(b))
    del scratch

    # -- art ------------------------------------------------------------------
    art_layer = None
    if art_mode == "lattice":
        # The art shares the layout's outer boundary: its top is the plate's top, its right edge the
        # margin. Candidate A is the corner strip right of the header row, down to the first line
        # that reaches into it; candidate B is the pocket below and right of the last lines that do.
        # Several left edges are tried and the largest zone wins (A before B, so a series shares
        # one silhouette).
        art_right = W - m
        top_a = header_y
        bottom_b = sig_top - ctx.px(24)
        min_w, min_h = ctx.px(180), ctx.px(130)      # room for at least one lattice triangle plus a trace
        best_a = best_b = None
        for frac in (0.52, 0.56, 0.60, 0.64, 0.68, 0.72, 0.76):
            x = int(math.ceil(frac * W))
            if art_right - x < min_w:
                break
            crossing = [p for p in placed if p.x1 + clear > x]
            bottom_a = content_bottom
            top_b = top_a
            for p in crossing:
                if p.y1 > top_a:
                    bottom_a = min(bottom_a, p.y0 - clear)
                top_b = max(top_b, p.y1 + clear)
            for slot, z in (("a", (x, top_a, art_right, bottom_a)), ("b", (x, top_b, art_right, bottom_b))):
                zw, zh = z[2] - z[0], z[3] - z[1]
                if zw < min_w or zh < min_h:
                    continue
                area = zw * zh
                if slot == "a" and (best_a is None or area > best_a[0]):
                    best_a = (area, z)
                if slot == "b" and (best_b is None or area > best_b[0]):
                    best_b = (area, z)
        chosen = best_a or best_b
        if chosen:
            zone = chosen[1]
            accent = T.sky if navy else None
            art_layer = constellation(canvas, zone, T.gold if navy else T.navy, accent, _seed(sp, sz), s)
            meta["art_zone"] = [int(v) for v in zone]
        else:
            meta["warnings"].append("no room for lattice art at this size")
    elif art_mode == "ghost":
        # the supergraphic (logos/README.md section 9): the mark cropped by the top edge, at least
        # 60 % of the height, right of the narrowed text column, never under text or logos
        mark = load_rgba(str(LOGOS["mark-white" if navy else "mark-navy"]))
        gy0 = -int(round(0.16 * H))
        gh = min(int(round(0.92 * H)), (sig_top - clear) - gy0)
        if ksu_rect:
            gh = 0
        if gh < 0.60 * H:
            meta["warnings"].append("ghost mark skipped: it needs at least 60 % of the height clear of logos "
                                    "(logos/README.md section 9)")
        else:
            gw = int(round(gh * mark.width / mark.height))
            ghost = with_alpha(mark.resize((gw, gh), Image.LANCZOS), 0.07 if navy else 0.05)
            ghost = ghost.crop((0, -gy0, gw, gh))          # the part below the top edge
            art_layer = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
            art_layer.alpha_composite(ghost, (int(0.64 * W), 0))
            canvas.alpha_composite(art_layer)
            meta["art_zone"] = "ghost mark"

    # -- stage panel and cut-out, or the image panel ------------------------------------
    if stage:
        px0, py0, px1, py1 = stage["panel"]
        rect(draw, px0, py0, px1 - px0, py1 - py0, T.white)
        ix0, iy0, ix1, iy1 = stage["rect"]
        im = fit_contain(stage["cut"], ix1 - ix0, iy1 - iy0)
        paste(canvas, im, ix1 - im.width, iy1 - im.height)
        meta["stage"] = {"illustration": [ix0, iy0, ix1, iy1], "panel": [px0, py0, px1, py1]}
    elif image is not None and img_rect:
        x0, y0, x1, y1 = img_rect
        pw, ph = x1 - x0, y1 - y0
        has_alpha = image.getchannel("A").getextrema()[0] < 255
        if has_alpha:
            rect(draw, x0, y0, pw, ph, T.mist)
            vy0 = max(y0, sz.ui_top)              # centre the cut-out in the part a story's UI leaves visible
            vh = y1 - vy0
            inset = int(round(0.07 * min(pw, vh)))
            im = fit_contain(image, pw - 2 * inset, vh - 2 * inset)
            paste(canvas, im, x0 + (pw - im.width) / 2, vy0 + (vh - im.height) / 2)
        else:
            paste(canvas, fit_cover(image, pw, ph), x0, y0)

    # -- band ---------------------------------------------------------------------
    hazard_band(canvas, "navy" if navy else "gold", band_y, band_h)

    # -- plate ---------------------------------------------------------------------
    draw = ImageDraw.Draw(canvas)
    if has_plate:
        rect(draw, plate_x, plate_y, P, P, ctx.c_plate)
        if tpl.name == "quote" and not number:
            qst = Style("slab-bold", int(P * 1.35), T.navy if navy else T.gold)
            f = face("slab-bold").font(qst.px)
            bb = ink_bbox(f, "“")           # tight ink box (getbbox clamps the bottom to the baseline)
            gw, gh = bb[2] - bb[0], bb[3] - bb[1]
            draw.text((plate_x + (P - gw) / 2 - bb[0], plate_y + (P - gh) / 2 - bb[1]), "“", font=f,
                      fill=qst.color, anchor="ls")
        elif number:
            nst = Style("slab-bold", int(round(P * 0.62)), T.navy if navy else T.gold, tracking=-0.01)
            ts = Typesetter(nst)
            nw = ts.width(number)
            cap = nst.metrics["cap"]
            ts.draw(draw, plate_x + (P - nw) / 2, plate_y + P / 2 + cap / 2, number)
        else:
            g = int(round(P * 0.80))
            ic = scaled(str(icon_path(icon, ctx.c_plate_glyph)), g, g)
            paste(canvas, ic, plate_x + (P - g) / 2, plate_y + (P - g) / 2)
        require_contrast(T.navy if navy else T.gold, ctx.c_plate, "plate glyph")

    # -- eyebrow + tag ---------------------------------------------------------------
    if eb_lines:
        ts = Typesetter(eyebrow_style)
        base = eyebrow_baseline()
        for line in eb_lines:
            ts.draw(draw, eb_x, base, line)
            base += eyebrow_style.pitch
    if tag_text:
        ts = Typesetter(tag_style)
        ts.draw(draw, tag_x, eyebrow_baseline(), tag_text)

    # -- big plate (video cover) ------------------------------------------------------
    if big_plate:
        bx, by, side = big_plate
        rect(draw, bx, by, side, side, ctx.c_plate)
        g = int(round(side * 0.72))
        ic = scaled(str(icon_path(icon, ctx.c_plate_glyph)), g, g)
        paste(canvas, ic, bx + (side - g) / 2, by + (side - g) / 2)

    # -- content -----------------------------------------------------------------------
    y = content_top
    text_rects = []
    for b in stack.blocks:
        text_rects += b.draw(canvas, stack.x, y, stack.width_for(b))
        y += b.measure(stack.width_for(b))

    # -- signatures (bottoms aligned on sig_bottom) ---------------------------------------
    draw = ImageDraw.Draw(canvas)
    atr_img = scaled(str(LOGOS[atr_key]), atr_w, atr_h)
    paste(canvas, atr_img, m, sig_bottom - atr_h)
    logo_rects = [Placed(m, sig_top, m + atr_w, sig_bottom)]
    if navy and ksu_shown:
        ksu = scaled(str(LOGOS["ksu-white"]), kw, kh)
        if ksu_rect:
            paste(canvas, ksu, ksu_rect[0], ksu_rect[1])
        else:
            paste(canvas, ksu, W - m - kw, sig_bottom - kh)
            logo_rects.append(Placed(W - m - kw, sig_top, W - m, sig_bottom))
    elif not navy:
        # the text credit: bottom-right, centred on the mark's height, or (staged) top right in the
        # header row where the wordmark goes on navy
        ts = Typesetter(credit_st)
        mm = credit_st.metrics
        if credit_rect:
            base = credit_rect[1] + mm["cap"]
            for line in credit_lines:
                ts.draw(draw, credit_rect[2] - ts.width(line), base, line)
                base += credit_st.pitch
        else:
            base = sig_bottom - atr_h + (atr_h - credit_h) / 2 + mm["cap"]
            logo_rects.append(Placed(credit_right - credit_w, sig_top, credit_right, sig_bottom))
            for line in credit_lines:
                ts.draw(draw, credit_right - ts.width(line), base, line)
                base += credit_st.pitch
    meta["signatures"] = {"mode": sig_mode, "atr_px": [atr_w, atr_h], "ksu_px": [kw, kh] if ksu_shown else [0, 0],
                          "ksu_position": ("top-right" if ksu_rect else "bottom-right") if ksu_shown else None,
                          "credit_position": (("top-right" if credit_rect else "bottom-right") if not navy else None)}

    # -- QA: art must never sit under text or logos; nothing in YouTube's badge corner ----------------
    keep = text_rects + header_rects + logo_rects
    if art_layer is not None:
        a = np.asarray(art_layer.getchannel("A"))
        for r in keep:
            x0, y0, x1, y1 = (max(0, int(r.x0)), max(0, int(r.y0)), min(W, int(math.ceil(r.x1))), min(H, int(math.ceil(r.y1))))
            if x1 > x0 and y1 > y0 and a[y0:y1, x0:x1].max() > 0:
                raise LayoutError(f"internal: art overlaps text or a logo at {x0},{y0}-{x1},{y1}")
        meta["art_pixels"] = int((a > 0).sum())
    if stage:
        ix0, iy0, ix1, iy1 = stage["rect"]
        for r in keep:
            if r.x1 > ix0 - clear + 1 and r.x0 < ix1 and r.y1 > iy0 - clear + 1 and r.y0 < iy1:
                raise LayoutError(f"internal: text or a logo at {r.x0:.0f},{r.y0:.0f}-{r.x1:.0f},{r.y1:.0f} overlaps "
                                  "the staged illustration")
    if sz.name == "youtube-thumb":
        bx, by = YT_BADGE[0] * W / 1280.0, YT_BADGE[1] * H / 720.0
        for r in keep + ([Placed(*img_rect)] if img_rect else []) + ([Placed(*stage["rect"])] if stage else []):
            if r.x1 > bx and r.y1 > by:
                raise LayoutError(f"internal: an element at {r.x0:.0f},{r.y0:.0f}-{r.x1:.0f},{r.y1:.0f} sits in "
                                  "YouTube's duration-badge corner")

    # -- safe-zone overlay (QA) --------------------------------------------------------------------
    if safe_zones:
        ov = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        od = ImageDraw.Draw(ov)
        od.rectangle([m, header_y, W - m - 1, sig_bottom - 1], outline=(255, 0, 255, 160), width=2)
        if sz.ui_top:
            od.rectangle([0, 0, W - 1, sz.ui_top - 1], fill=(255, 0, 0, 50))
        if sz.ui_bottom:
            od.rectangle([0, H - sz.ui_bottom, W - 1, H - 1], fill=(255, 0, 0, 50))
        if sz.name == "youtube-thumb":
            od.rectangle([int(YT_BADGE[0] * W / 1280.0), int(YT_BADGE[1] * H / 720.0), W - 1, H - 1], fill=(255, 0, 0, 50))
        if isinstance(meta.get("art_zone"), list):
            x0, y0, x1, y1 = meta["art_zone"]
            od.rectangle([x0, y0, x1 - 1, y1 - 1], outline=(0, 255, 255, 160), width=2)
        od.rectangle([col_x, content_top, col_x + col_w - 1, content_bottom - 1], outline=(0, 255, 0, 140), width=2)
        if stage:
            ix0, iy0, ix1, iy1 = stage["rect"]
            od.rectangle([ix0, iy0, ix1 - 1, iy1 - 1], outline=(0, 255, 255, 160), width=2)
            px0, py0, px1, py1 = stage["panel"]
            od.rectangle([px0, py0, px1 - 1, py1 - 1], outline=(255, 0, 255, 100), width=2)
        for r in keep:
            od.rectangle([r.x0, r.y0, r.x1, r.y1], outline=(255, 255, 0, 120), width=1)
        canvas.alpha_composite(ov)

    meta["alt_text"] = str(sp.get("alt_text") or compose_alt(sp, tpl))
    meta["alt_note"] = alt_lead_note(meta["alt_text"], sp, tpl)
    meta["alt_has_placeholders"] = bool(PLACEHOLDER_RE.search(meta["alt_text"]))
    meta["seed"] = _seed(sp, sz)
    return canvas.convert("RGB"), meta


def render_to_files(spec: dict, out: str, sizes: Optional[Iterable[str]] = None, allow_placeholders: bool = False,
                    safe_zones: bool = False, write_alt: bool = True, quiet: bool = False,
                    suffix: bool = False, base_dir: Optional[Path] = None) -> list:
    """Render to <out> (one size; sizes=None or one name) or, with suffix=True, to
    <stem>-<size>.png for every name in sizes. Returns the written paths."""
    out = Path(out)
    if out.suffix.lower() != ".png":
        out = out.with_suffix(".png")
    stem = out.with_suffix("")
    sizes = list(sizes) if sizes else [None]
    written = []
    failures = []
    for sname in sizes:
        target = Path(f"{stem}-{sname}.png") if suffix else out
        try:
            img, meta = render(spec, sname, allow_placeholders, safe_zones, base_dir)
        except (LayoutError, SpecError, ContrastError) as exc:
            failures.append((sname or spec.get("size") or "default", exc))
            if not quiet:
                print(f"FAIL {target.name}: {exc}", file=sys.stderr)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        img.save(target, "PNG", optimize=True)
        written.append(str(target))
        if write_alt:
            alt = meta["alt_text"]
            if meta.get("alt_has_placeholders"):
                alt = re.sub(r"(?<!\.)\.\.(?!\.)", ".", re.sub(r"\[([^\[\]]*)\]", r"\1", alt))
                meta["warnings"].append("alt text contains placeholders (brackets removed in the sidecar): "
                                        "replace them before posting")
            target.with_suffix(".txt").write_text(alt + "\n")
            if meta.get("alt_note"):
                meta["warnings"].append(meta["alt_note"])
        if not quiet:
            fit = " ".join(f"{k} {v}px" for k, v in meta.get("fit", {}).items())
            sig = meta.get("signatures", {})
            sig_s = f"  sig {sig.get('mode', '?')} {sig.get('atr_px', ['?', '?'])[1]}px"
            if sig.get("ksu_position"):
                sig_s += f" KSU {sig['ksu_px'][0]}px {sig['ksu_position']}"
            alt_s = f"  alt {len(meta['alt_text'])} chars" if write_alt else ""
            warn = ("  ! " + "; ".join(meta["warnings"])) if meta["warnings"] else ""
            print(f"ok   {target.name}  {meta['px'][0]}x{meta['px'][1]}  {fit}{sig_s}{alt_s}{warn}")
    if failures and not written:
        # keep the exception class so the CLI exit codes hold (spec error 1, layout/contrast 2)
        excs = [e for _, e in failures]
        for cls in (PlaceholderError, SpecError, ContrastError):
            if all(isinstance(e, cls) for e in excs):
                raise cls("; ".join(f"{s}: {e}" for s, e in failures))
        raise LayoutError("; ".join(f"{s}: {e}" for s, e in failures))
    return written


