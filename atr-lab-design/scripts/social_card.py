def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Render ATR Lab social graphics from a JSON spec.",
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog="See the module docstring for the spec format.")
    ap.add_argument("spec", nargs="?", help="JSON spec file")
    ap.add_argument("-o", "--out", help="output PNG (default: <spec stem>.png in the current directory)")
    ap.add_argument("--outdir", help="directory for the output (default: the directory of -o, else the "
                                     "current directory)")
    ap.add_argument("--size", help="override the spec's size")
    ap.add_argument("--sizes", help="comma-separated sizes to render as <stem>-<size>.png")
    ap.add_argument("--all-sizes", action="store_true", help="render every size as <stem>-<size>.png")
    ap.add_argument("--allow-placeholders", action="store_true", help="render [bracketed] placeholders")
    ap.add_argument("--safe-zones", action="store_true", help="draw margins, UI, badge and art zones (QA)")
    ap.add_argument("--no-alt", action="store_true", help="do not write the alt-text sidecar")
    ap.add_argument("--validate", action="store_true", help="validate the spec and exit")
    ap.add_argument("--list-templates", action="store_true")
    ap.add_argument("--list-sizes", action="store_true")
    ap.add_argument("--list-icons", action="store_true")
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--version", action="version", version=__version__)
    a = ap.parse_args(argv)

    if a.list_templates:
        _list_templates()
        return 0
    if a.list_sizes:
        _list_sizes()
        return 0
    if a.list_icons:
        print("\n".join(icon_names()))
        return 0
    if not a.spec:
        ap.print_help()
        return 1
    try:
        spec = json.loads(Path(a.spec).read_text())
    except (OSError, json.JSONDecodeError) as exc:
        print(f"error: cannot read spec {a.spec}: {exc}", file=sys.stderr)
        return 1
    base_dir = Path(a.spec).resolve().parent      # relative "image" paths also resolve from here
    try:
        tpl, sz, bg, unknown = validate_spec(spec, a.size, a.allow_placeholders, base_dir)
        if unknown:
            print(f"warning: ignored unknown fields: {', '.join(unknown)}", file=sys.stderr)
        if a.validate:
            print(f"ok: {tpl.name} at {sz.name} on {bg}")
            return 0
        stem = Path(a.out) if a.out else Path.cwd() / (Path(a.spec).stem + ".png")
        if a.outdir:
            stem = Path(a.outdir) / stem.name
        many = list(SIZES) if a.all_sizes else [x.strip() for x in a.sizes.split(",") if x.strip()] if a.sizes else None
        if many:
            bad = [x for x in many if x not in SIZES]
            if bad:
                raise SpecError(f"unknown size(s) {', '.join(bad)}; choose from: {', '.join(SIZES)}")
            written = render_to_files(spec, stem, many, a.allow_placeholders, a.safe_zones,
                                      not a.no_alt, a.quiet, suffix=True, base_dir=base_dir)
            return 0 if len(written) == len(many) else 2
        render_to_files(spec, stem, [a.size] if a.size else None, a.allow_placeholders, a.safe_zones,
                        not a.no_alt, a.quiet, base_dir=base_dir)
        return 0
    except PlaceholderError as exc:
        print(f"refused: {exc}", file=sys.stderr)
        return 3
    except SpecError as exc:
        print(f"spec error: {exc}", file=sys.stderr)
        return 1
    except (LayoutError, ContrastError) as exc:
        print(f"layout error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
