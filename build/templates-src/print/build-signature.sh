#!/bin/bash
# email-signature.html / .txt: generated with the skill's own generator (atr-lab-design/scripts/email_signature.py)
# so the shipped template and the tool students run stay identical. Placeholders in [brackets]; the logo is a
# hosted-URL placeholder with alt text; verified handles only.
set -euo pipefail
ROOT="/Users/marcodotio/Developer/atr-lab-design-skill"
SCRATCH="/private/tmp/claude-501/-Users-marcodotio-Developer-atr-lab-design-skill/80375296-6f20-4da8-a711-62359143039a/scratchpad"
TPL="$ROOT/atr-lab-design/assets/templates"
QA="$ROOT/build/qa/print"
GEN="$ROOT/atr-lab-design/scripts/email_signature.py"
WORK="$SCRATCH/signature"; mkdir -p "$WORK" "$QA"

python3 "$GEN" \
  --name "[Full Name]" --pronouns "[pronouns, optional]" \
  --title "[Title, e.g. Graduate Research Assistant]" \
  --email "[user]@kent.edu" --phone "330-672-[xxxx]" \
  --social default \
  --logo ksu --logo-url "https://[your-host]/signature/ksu-horizontal-logo.png" --logo-width 180 \
  --font calibri --out "$WORK/email-signature" 2> "$WORK/generator.log" || true
cat "$WORK/generator.log"

# Prepend a how-to block (HTML comments survive the paste into most signature editors; nothing outside the
# table matters once pasted) and ship the pair.
{
cat <<'EOF'
<!--
ATR Lab email signature template (Advanced Telerobotics Research Lab, Kent State University)
Generated by atr-lab-design/scripts/email_signature.py; regenerate with your own values instead of editing by hand:
  python3 scripts/email_signature.py --name "Jane Doe" --title "Graduate Research Assistant" --email jdoe@kent.edu \
      --phone 330-672-1234 --social default --logo ksu --logo-url https://<host>/signature/ksu-horizontal-logo.png \
      --logo-file ksu-horizontal-logo.png --out my-signature

HOW TO USE
1. Replace every [bracketed] placeholder (name, pronouns line or delete it, title, email, phone).
2. Logo: host the official two-color Kent State HORIZONTAL logo (from UCM / kent.edu/brand/logos, PNG, exported at
   2x = 360 px wide) at a stable https:// address and put that URL in the img src. width="180" height="52" encode
   that file's 3.4:1 ratio; the stacked wordmark in assets/logos/ksu is about 1:1 and would render squashed, so do
   not host that file. If you use any other image, regenerate with --logo-file <the same file> so the script
   measures its ratio and writes matching width and height. Keep the alt text. For dark-mode safety put it on a white tile first: scripts/email_signature.py --make-tile
   ksu-horizontal-logo.png ksu-logo-tile.png --tile white --tile-width 200 (then use --logo-width 200 --logo-file).
   The standard signature has no ATR image: the lab is the navy text line (UCM template field order).
3. Open this file in a browser, select all, copy, paste into Outlook / Gmail / Apple Mail signature settings.
   Use email-signature.txt for plain-text mail.

RULES BAKED IN (references/web-and-digital.md section 3, references/kent-state-compliance.md section 15)
- Web-safe fonts only (Calibri, Arial, Helvetica): Kent State's email guidance; brand fonts do not load in mail.
- Live text for every fact; one PNG/JPG image with alt text and numeric width/height (Outlook ignores CSS sizing);
  no SVG, WebP, GIF, CSS backgrounds or <style> blocks (Outlook for Windows and Gmail).
- Dark mode: Outlook for Windows and Gmail ignore prefers-color-scheme and invert colors themselves, so the
  signature uses no background colours, navy/ink/slate text (>= 4.5:1 on white) and a logo on a white tile.
- Verified channels only: atr.cs.kent.edu, X @atrlab_kent, GitHub ATR-Lab, the lab YouTube channel. Never the
  handle printed in the old 2021 slide footer (it does not exist; the checker rejects it).
- No funder logos in signatures (NSF forbids it; NASA/DoD marks need permission).
-->
EOF
# Every row, including "Follow the lab", is 14 px (Kent State's email guidance: 14 px body text); the
# generator writes that directly, so the fragment is shipped as generated.
cat "$WORK/email-signature.html"
} > "$TPL/email-signature.html"
cp "$WORK/email-signature.txt" "$TPL/email-signature.txt"
cp "$WORK/email-signature-preview.html" "$QA/email-signature-preview.html"
python3 "$GEN" --check "$TPL/email-signature.html" || true
echo "wrote $TPL/email-signature.html and .txt; preview at $QA/email-signature-preview.html"
